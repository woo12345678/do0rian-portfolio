const assert=require('node:assert/strict');
const fs=require('node:fs');
const base='games/ttak-club/v1.0.3';
const app=fs.readFileSync(`${base}/js/app.js`,'utf8');
const html=fs.readFileSync(`${base}/index.html`,'utf8');
const css=fs.readFileSync(`${base}/css/style.css`,'utf8');
const sw=fs.readFileSync(`${base}/sw.js`,'utf8');

assert.match(html,/id="golfHoles"/,'Golf setup has its own round-length control');
assert.match(html,/<option value="3" selected>3홀<\/option>/);
assert.match(html,/<option value="9">9홀<\/option>/);
assert.match(html,/id="golfMinimap"[^>]+tabindex="0"[^>]+aria-describedby="golfMapText"/,'minimap is keyboard reachable and described');
assert.match(html,/id="golfMapText" class="sr-only"/,'minimap has a nonvisual course description');
assert.match(app,/mode==='golf'\?\{holes:\+\$\('#golfHoles'\)\.value\}/,'selected Golf hole count reaches game settings');
assert.match(app,/function updateGolfCamera\(/,'Golf has a following camera');
assert.match(app,/golfCamera\.x/,'pointer/rendering use camera position');
assert.match(app,/function drawGolfMinimap\(/,'Golf provides a whole-course minimap');
assert.match(app,/par:game\.board\.par/,'Golf HUD exposes par');
assert.match(app,/game\.settings\.holes/,'Golf HUD exposes selected hole count');
assert.match(app,/function golfHistorySummary\(/,'completed hole scores remain inspectable');
assert.match(app,/function golfMapDescription\(/,'minimap exposes semantic course directions and hazards');
assert.match(app,/Full golf course map/,'minimap accessible name is localized in English');
assert.match(app,/3 Holes/,'English setup localizes the three-hole option');
assert.match(app,/9 Holes/,'English setup localizes the nine-hole option');
assert.match(app,/파는 숙련된 기준 타수/,'Korean guide explains par for beginners');
assert.match(app,/물에 빠지면 1벌타/,'Korean guide explains water penalties');
assert.match(css,/\.golf-minimap/,'minimap is styled');
assert.match(css,/\.canvaswrap #board\{width:auto/,'compact landscape sizing only targets the game board');
assert.doesNotMatch(css,/\.canvaswrap canvas\{width:auto/,'minimap must not inherit full-height compact board sizing');
assert.match(sw,/ttak-static-v1\.0\.3-golf-tour-19/,'Golf tour update invalidates the offline cache');

console.log('ttak golf UI tests passed');
